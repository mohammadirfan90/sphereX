def make_irsa_query_provenance(
    *,
    collection: str,
    release: str,
    doi: str,
    queried_at: str,
    query_url: str,
    cone_search: str,
    product_count: int,
    entity_label: str,
    unified_object_id: Optional[str] = None,
) -> W3CProvBlock:
    """PROV-DM bundle for an IRSA SIA / TAP query."""
    e_query = W3CProvEntity(
        entity_id=f"entity:irsa_query:{uuid.uuid4()}",
        entity_type="query:irsa_sia",
        label=entity_label,
        attributes={
            "collection": collection,
            "release": release,
            "doi": doi,
            "cone_search": cone_search,
            "query_url": query_url,
            "product_count": product_count,
        },
    )
    a_query = W3CProvActivity(
        activity_id=f"activity:irsa_query:{uuid.uuid4()}",
        activity_type="query:irsa_sia",
        started_at=queried_at,
        ended_at=queried_at,
        used=[e_query.entity_id],
        attributes={
            "service": "NASA/IPAC IRSA SIA",
            "service_url": "https://irsa.ipac.caltech.edu/SIA",
        },
    )
    ag_irsa = W3CProvAgent(
        agent_id="agent:irsa",
        agent_type="service:irsa",
        label="NASA/IPAC Infrared Science Archive",
        attributes={"homepage": "https://irsa.ipac.caltech.edu"},
    )
    return provenance_service.record(
        entities=[e_query],
        activities=[a_query],
        agents=[ag_irsa],
        unified_object_id=unified_object_id,
        primary_role="primary",
    )


